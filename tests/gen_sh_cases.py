# ---- Running them ----

ENV = {"PATH": "/usr/bin:/bin", "LC_ALL": "C"}

def run(argv, script, stdin, mode):
    d = tempfile.mkdtemp(prefix="shcase")
    try:
        if mode == C:
            args, inp = argv + ["-c", script], stdin
        elif mode == S:
            args, inp = argv + ["-s"], script
        else:
            args, inp = argv + ["-i"], script
        if inp is not None and not inp.endswith("\n") and mode != C:
            inp += "\n"
        p = subprocess.run(args, input=(inp or "").encode("latin-1"), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                           cwd=d, env=ENV, timeout=20)
        return p.stdout, p.returncode, bool(p.stderr)
    except subprocess.TimeoutExpired:
        return b"<timeout>", -1, False
    finally:
        shutil.rmtree(d, ignore_errors=True)

def reference():
    out = []
    dash = shutil.which("dash")
    for script, stdin, modes, ref in CASES:
        if not modes:
            continue
        m = C if modes & C else S
        o, st, err = run(["bash", "--posix"], script, stdin, m)
        if ref == "dash":
            o, st, err = run([dash or "dash"], script, stdin, m)
        elif dash:
            o2, st2, _ = run([dash], script, stdin, m)
            if (o2, st2) != (o, st):
                print(f"bash and dash differ: {script!r}\n  bash {st} {o!r}\n  dash {st2} {o2!r}", file=sys.stderr)
        out.append((script, stdin, modes, o, st, err))
    return out

def c_str(b):
    if isinstance(b, str):
        b = b.encode("latin-1")
    s = '"'
    for c in b:
        if c == 0x22 or c == 0x5C:
            s += "\\" + chr(c)
        elif 32 <= c < 127 and c != ord("?"):
            s += chr(c)
        else:
            s += "\\%03o" % c
    return s + '"'

def write_header(rows):
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "sh_cases.h"), "w") as f:
        f.write("// Generated by gen_sh_cases.py: what bash --posix (or dash) did. Do not edit.\n")
        f.write("typedef struct { const char* script; const char* in; int has_in; int modes; const char* out; int outn; int status; int err; } sh_case_t;\n")
        f.write("enum { MODE_C = 1, MODE_S = 2, MODE_I = 4 };\n")
        f.write("static const sh_case_t sh_cases[] = {\n")
        for script, stdin, modes, o, st, err in rows:
            f.write("    { %s, %s, %d, %d, %s, %d, %d, %d },\n" % (c_str(script), c_str(stdin or ""), stdin is not None, modes,
                                                            c_str(o), len(o), st, int(err)))
        f.write("};\n")
    print(f"{len(rows)} cases", file=sys.stderr)

def check(sh):
    bad = 0
    for script, stdin, modes, o, st, err in reference():
        for m, name in ((C, "-c"), (S, "stdin"), (I, "-i")):
            if not modes & m:
                continue
            o2, st2, err2 = run([sh], script, stdin, m)
            if (o2, st2) != (o, st) or (m == C and err2 != err):
                bad += 1
                print(f"--- {name}: {script!r}" + (f" <<< {stdin!r}" if stdin else ""))
                print(f"  want {st} err={err} {o!r}")
                print(f"  got  {st2} err={err2} {o2!r}")
    print(f"{bad} differences")

if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        check(os.path.abspath(sys.argv[2]))
    else:
        write_header(reference())
