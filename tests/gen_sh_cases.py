#!/usr/bin/env python3
"""Writes sh_cases.h: shell scripts, with what `bash --posix` wrote on
standard output and its exit status, for test_sh to run the shell's core
(src/programs/lib/shcore.c) against. Each case runs in an empty directory
of its own. The generated file is checked in; rerun this only to change the
cases. dash is run too where it is installed, and a case where the two
shells disagree is reported, since that usually means the case tests
something POSIX leaves open.

  gen_sh_cases.py             write sh_cases.h
  gen_sh_cases.py --check SH  run SH (sh_host) on every case and show what differs

What standard error says is not compared (each shell words its messages its
own way), only whether something was written there when bash wrote nothing,
or nothing when it did.

Modes: C runs the case as `sh -c SCRIPT`; S feeds the script on standard
input; I feeds it on standard input with -i, through sh_feed as the prompt
does. A case with input for the script itself runs only as C."""
import os, shutil, subprocess, sys, tempfile

C, S, I = 1, 2, 4
ALL = C | S | I

# (script, input or None, modes)
CASES = []

# ref: whose answer is right where bash and dash differ. dash's, mostly
# for the status a script stops with on an error (POSIX: the shell exits).
def case(script, stdin=None, modes=None, ref="bash"):
    if modes is None:
        modes = C if stdin is not None else ALL
    CASES.append((script, stdin, modes, ref))

def only_c(script, stdin=None, ref="bash"):
    case(script, stdin, C, ref)

