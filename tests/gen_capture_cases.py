#!/usr/bin/env python3
"""Writes capture_cases.h: patterns with groups, and where GNU sed (LC_ALL=C)
says each group matched, over the same fixed lines as gen_regex_cases.py.
Needs GNU sed. The generated file is checked in; rerun this only to change
the cases.

The oracle is `sed 's/PAT/<mark>&<mark>\\1<mark>\\2.../'`: the first match of
each line, with the text of every group. sed prints an empty string for a
group that took no part, so the test treats "no part" and "empty" alike."""
import os, random, re, subprocess, sys, tempfile

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "gen_regex_cases.py")).read()
src = src[:src.rindex("main()")]  # the generator's helpers, without running it
g = {}
exec(compile(src, "gen_regex_cases", "exec"), g)
LINES = g["LINES"]

def ngroups(pat, ere):
    n, i, inset = 0, 0, False
    while i < len(pat):
        c = pat[i]
        if inset:
            if c == "[" and pat[i + 1:i + 2] in (":", ".", "="):  # [:alpha:]
                j = pat.find(pat[i + 1] + "]", i + 2)
                i = j + 2 if j >= 0 else i + 1
                continue
            if c == "]":
                inset = False
        elif c == "[":
            inset = True
            if pat[i + 1:i + 2] == "^": i += 1
            if pat[i + 1:i + 2] == "]": i += 1
        elif c == "\\":
            if not ere and pat[i + 1:i + 2] == "(": n += 1
            i += 1
        elif ere and c == "(":
            n += 1
        i += 1
    return n

def cstr(s):
    return '"' + "".join({"\\": "\\\\", '"': '\\"', "\n": "\\n", "\t": "\\t"}.get(c, c) for c in s) + '"'

def oracle(flags, pat, ng, path):
    rep = "\x01&\x02" + "".join("\\%d\x03" % k for k in range(1, ng + 1))
    script = f"s/{pat}/{rep}/"
    try:
        p = subprocess.run(["sed"] + (["-E"] if "E" in flags else []) + [script, path],
                           capture_output=True, env={"LC_ALL": "C"}, timeout=3)
    except subprocess.TimeoutExpired:
        return None
    if p.returncode: return None
    out = p.stdout.decode("latin-1").split("\n")[:-1]
    if len(out) != len(LINES): return None
    parts = []
    for k, l in enumerate(out):
        if "\x01" not in l: continue
        pre, rest = l.split("\x01", 1)
        whole, rest = rest.split("\x02", 1)
        grp = rest.split("\x03")
        grp, post = grp[:ng], grp[ng]
        parts.append("%d:%d-%d" % (k, len(pre), len(pre) + len(whole)) + "".join("|" + t for t in grp))
    return ";".join(parts)

def main():
    random.seed(20240611)
    cases = [c for c in g["FIXED"] if "F" not in c[0] and "w" not in c[0] and "x" not in c[0] and "\n" not in c[1]]
    cases += [("", r"\(a\)\(b\)"), ("E", "(a)(b)?"), ("E", "(a|ab)(c|bcd)(d*)"), ("E", "(a*)(b*)"), ("E", "(a*)*"),
              ("E", "(a|b)*"), ("E", "(a?)+"), ("E", "((a)|(b))+"), ("E", "(.)(.)(.)"), ("E", "(a)|(b)|(c)"),
              ("E", "(a*)+"), ("E", "(a|b)+c"), ("E", "x*(a|b)?"), ("", r"\(a*\)*"), ("", r"\(\(a\)\|\(b\)\)*"),
              ("E", "(foo|foo bar)( baz)?"), ("E", "([a-z]+) ([a-z]+)"), ("E", "(^| )(b)( |$)"), ("E", "(b|)a"), ("E", "(|b)a")]
    for _ in range(900):
        ere = random.random() < 0.5
        fl = "E" if ere else ""
        cases.append((fl, g["alt"](ere, 0, True)))
    d = tempfile.mkdtemp()
    path = os.path.join(d, "corpus")
    open(path, "wb").write(("\n".join(LINES) + "\n").encode("latin-1"))
    rows, seen = [], set()
    for fl, pat in cases:
        fl = "".join(c for c in fl if c in "Ei")
        if "i" in fl: continue
        if (fl, pat) in seen or "/" in pat: continue
        seen.add((fl, pat))
        ng = ngroups(pat, "E" in fl)
        if ng == 0 or ng > 9: continue
        exp = oracle(fl, pat, ng, path)
        if exp is None: continue
        rows.append((fl, pat, ng, exp))
    with open(os.path.join(here, "capture_cases.h"), "w") as f:
        f.write("// Generated by gen_capture_cases.py from GNU sed's answers. Do not edit.\n")
        f.write("typedef struct { const char* flags; const char* pat; int ngroups; const char* want; } ccase_t;\n")
        f.write("static const ccase_t ccases[] = {\n")
        for fl, pat, ng, exp in rows:
            f.write("    { %s, %s, %d, %s },\n" % (cstr(fl), cstr(pat), ng, cstr(exp)))
        f.write("};\n")
    print(len(rows), "cases with groups")

main()
