#!/usr/bin/env python3
"""Writes crypto_cases.h: inputs and the right answers for SHA-256, HMAC,
HKDF, ChaCha20, Poly1305, ChaCha20-Poly1305, X25519, AES-128 and
AES-128-GCM. The generated file
is checked in, so test_crypto needs nothing but a compiler; rerun this only
to change the cases.

    python3 tests/gen_crypto_cases.py WYCHEPROOF_DIR

Two sources. Project Wycheproof's test vectors (github.com/C2SP/wycheproof,
Apache 2.0; WYCHEPROOF_DIR is its testvectors_v1 directory), which were
written to trip implementations on the edge cases: carries that almost never
happen, public keys chosen to hit zero in the middle of the arithmetic, tags
changed in one bit. And answers worked out here by OpenSSL, through Python's
hashlib and `cryptography` package, for random inputs of every awkward
length."""
import hashlib, json, os, random, sys
from cryptography.hazmat.primitives import poly1305
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM, ChaCha20Poly1305

random.seed(8446)
rb = lambda n: bytes(random.getrandbits(8) for _ in range(n))

def load(d, name):
    j = json.load(open(os.path.join(d, name)))
    for g in j["testGroups"]:
        for t in g["tests"]:
            yield g, t

def main():
    wp = sys.argv[1]
    out = ["// Generated by gen_crypto_cases.py. Do not edit.",
           "// The hmac, hkdf, aead and x25519 cases are from Project Wycheproof",
           "// (github.com/C2SP/wycheproof, Apache License 2.0); the rest are answers",
           "// from OpenSSL for random inputs. Bytes are written as hex.",
           "typedef struct { const char* f[7]; unsigned n; int ok; } crypto_case_t;"]

    def table(name, rows):
        out.append("static const crypto_case_t %s[] = {" % name)
        for fields, n, ok in rows:
            fs = ", ".join('"%s"' % (x.hex() if isinstance(x, bytes) else x) for x in fields)
            out.append("    {{%s}, %uu, %d}," % (fs, n, ok))
        out.append("};")
        print(name, len(rows))

    # SHA-256: every length around the block and padding boundaries, and some long ones.
    rows = []
    for n in list(range(0, 200)) + [255, 256, 257, 1000, 4095, 4096, 4097, 20000]:
        m = rb(n)
        rows.append(([m, hashlib.sha256(m).digest()], 0, 1))
    table("sha256_cases", rows)

    # HMAC: key, message, tag (some cut short), and whether the tag is right.
    rows = []
    for g, t in load(wp, "hmac_sha256_test.json"):
        rows.append(([bytes.fromhex(t["key"]), bytes.fromhex(t["msg"]), bytes.fromhex(t["tag"])],
                     g["tagSize"] // 8, t["result"] == "valid"))
    table("hmac_cases", rows)

    # HKDF: ikm, salt, info, output; n is the size asked for; not ok means it must be refused.
    rows = []
    for g, t in load(wp, "hkdf_sha256_test.json"):
        rows.append(([bytes.fromhex(t["ikm"]), bytes.fromhex(t["salt"]), bytes.fromhex(t["info"]),
                      bytes.fromhex(t["okm"])], t["size"], t["result"] == "valid"))
    table("hkdf_cases", rows)

    # ChaCha20 alone: key, nonce, input, output; n is the starting block.
    rows = []
    for n in list(range(0, 70)) + [127, 128, 129, 191, 192, 193, 255, 256, 257, 1000, 4096]:
        key, nonce, data = rb(32), rb(12), rb(n)
        ctr = random.choice([0, 1, 2, 7, 0x7fffffff, 0xffffff00, random.getrandbits(32) & 0xffffff00])
        c = Cipher(algorithms.ChaCha20(key, ctr.to_bytes(4, "little") + nonce), None).encryptor()
        rows.append(([key, nonce, data, c.update(data)], ctr, 1))
    table("chacha20_cases", rows)

    # Poly1305 alone: key, message, tag. Besides random ones, keys and
    # messages full of ones, to push the carries as far as they go.
    rows = []
    def p1305(key, m):
        return poly1305.Poly1305.generate_tag(key, m)
    for n in list(range(0, 70)) + [127, 128, 129, 255, 256, 1000]:
        key, m = rb(32), rb(n)
        rows.append(([key, m, p1305(key, m)], 0, 1))
    for n in [1, 15, 16, 17, 31, 32, 33, 48, 64, 160]:
        for key in [b"\xff" * 32, b"\xff" * 16 + bytes(16), bytes(16) + b"\xff" * 16, b"\x01" + bytes(31),
                    b"\x02" + bytes(15) + b"\xff" * 16, b"\xff" * 16 + b"\x01" + bytes(15)]:
            for m in [b"\xff" * n, bytes(n), (b"\xfb" + b"\xff" * 15) * (n // 16 + 1)]:
                m = m[:n]
                rows.append(([key, m, p1305(key, m)], 0, 1))
    table("poly1305_cases", rows)

    # The AEAD: key, nonce, aad, plain, cipher, tag; not ok means opening must fail.
    rows = []
    for g, t in load(wp, "chacha20_poly1305_test.json"):
        if g["ivSize"] != 96:
            continue  # nonces of the wrong size: the interface here cannot even express them
        rows.append(([bytes.fromhex(t[k]) for k in ("key", "iv", "aad", "msg", "ct", "tag")], 0, t["result"] == "valid"))
    for n in list(range(0, 40)) + [63, 64, 65, 255, 256, 257, 16385]:
        key, nonce, aad, m = rb(32), rb(12), rb(random.choice([0, 5, 5, 5, 13, 16, 17, 40])), rb(n)
        ct = ChaCha20Poly1305(key).encrypt(nonce, m, aad)
        rows.append(([key, nonce, aad, m, ct[:-16], ct[-16:]], 0, 1))
    table("aead_cases", rows)

    # X25519: their public value, our secret, the shared result. All of these must
    # come out as given, whatever odd public value was sent.
    rows = []
    for g, t in load(wp, "x25519_test.json"):
        rows.append(([bytes.fromhex(t["public"]), bytes.fromhex(t["private"]), bytes.fromhex(t["shared"])], 0, 1))
    table("x25519_cases", rows)

    # AES-128 alone, two blocks at a time as the code does it: key, in, out.
    # FIPS 197's example (C.1), keys of all zeros and all ones, then random.
    rows = []
    fips = bytes.fromhex("00112233445566778899aabbccddeeff")
    keys = [bytes(range(16)), bytes(16), b"\xff" * 16] + [rb(16) for _ in range(60)]
    for i, key in enumerate(keys):
        data = fips + rb(16) if i == 0 else rb(32) if i % 3 else bytes(32) if i % 2 else b"\xff" * 32
        rows.append(([key, data, Cipher(algorithms.AES(key), modes.ECB()).encryptor().update(data)], 0, 1))
    table("aes_cases", rows)

    # AES-128-GCM, laid out like aead_cases: key, nonce, aad, plain, cipher, tag.
    rows = []
    for g, t in load(wp, "aes_gcm_test.json"):
        if g["keySize"] != 128 or g["ivSize"] != 96 or g["tagSize"] != 128:
            continue  # TLS uses 128-bit keys and 96-bit nonces only
        rows.append(([bytes.fromhex(t[k]) for k in ("key", "iv", "aad", "msg", "ct", "tag")], 0, t["result"] == "valid"))
    for n in list(range(0, 50)) + [63, 64, 65, 95, 96, 97, 255, 256, 257, 16385]:
        key, nonce, aad, m = rb(16), rb(12), rb(random.choice([0, 5, 5, 5, 13, 16, 17, 40])), rb(n)
        ct = AESGCM(key).encrypt(nonce, m, aad)
        rows.append(([key, nonce, aad, m, ct[:-16], ct[-16:]], 0, 1))
    table("gcm_cases", rows)

    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, "crypto_cases.h"), "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
